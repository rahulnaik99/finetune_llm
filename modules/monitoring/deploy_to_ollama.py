"""
deploy_to_ollama.py  — close the loop (the D in the roadmap)
────────────────────────────────────────────────────────────
Take the fine-tuned MLX model and serve it in Ollama WITH your extended 16k
context, so the flywheel's next round can use the fine-tuned student.

Pipeline:
  1. FUSE    adapter + base  → a standalone MLX model  (mlx_lm.fuse)
  2. CONVERT MLX → GGUF        (uses llama.cpp's convert_hf_to_gguf.py)
  3. QUANTIZE GGUF (optional)  → Q4_K_M for fast local inference
  4. MODELFILE with `num_ctx 16384`  ← your -16k context is re-applied HERE
  5. ollama create             → nemotron-bolt-e4b-16k-trading

The context window is a RUNTIME setting (num_ctx), not part of the weights —
fine-tuning never changes it, so we simply set it again in the Modelfile.

This file writes the Modelfile and prints the exact commands. The MLX→GGUF
conversion needs llama.cpp checked out locally (one-time).

Usage:
    python deploy_to_ollama.py --adapter output/adapters/round_05 \
        --base mlx-community/NVIDIA-Nemotron-3.5-Bolt-E4B-OptiQ-4bit \
        --name nemotron-bolt-e4b-16k-trading --ctx 16384
"""
from __future__ import annotations
import argparse, subprocess, sys
from pathlib import Path


def write_modelfile(gguf_path: str, ctx: int, out="Modelfile") -> str:
    content = f"""# Auto-generated by deploy_to_ollama.py
FROM {gguf_path}
PARAMETER num_ctx {ctx}
PARAMETER temperature 0.2
SYSTEM \"\"\"You are a disciplined NSE equity trader. Protect capital first. Output JSON only.\"\"\"
"""
    Path(out).write_text(content)
    print(f"  Wrote {out} (num_ctx={ctx})")
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--adapter", required=True, help="output/adapters/round_XX (has adapters/ and/or fused_model/)")
    p.add_argument("--base", default="mlx-community/NVIDIA-Nemotron-3.5-Bolt-E4B-OptiQ-4bit")
    p.add_argument("--name", default="nemotron-bolt-e4b-16k-trading")
    p.add_argument("--ctx", type=int, default=16384)
    p.add_argument("--llamacpp", default="../llama.cpp", help="path to a llama.cpp checkout")
    p.add_argument("--run", action="store_true", help="actually execute the steps (needs tools installed)")
    a = p.parse_args()

    adapter = Path(a.adapter)
    fused = adapter / "fused_model"
    gguf = adapter / "model.gguf"

    steps = [
        # 1. fuse (skip if fused_model already exists)
        (["python", "-m", "mlx_lm.fuse", "--model", a.base,
          "--adapter-path", str(adapter / "adapters"), "--save-path", str(fused)],
         f"fuse adapter → {fused}", fused.exists()),
        # 2. MLX/HF safetensors → GGUF
        (["python", f"{a.llamacpp}/convert_hf_to_gguf.py", str(fused),
          "--outfile", str(gguf), "--outtype", "q8_0"],
         f"convert → {gguf}", False),
        # 3. (optional) quantize to Q4_K_M
        ([f"{a.llamacpp}/llama-quantize", str(gguf),
          str(adapter / 'model-q4.gguf'), "Q4_K_M"],
         "quantize → Q4_K_M", False),
    ]

    print("Deploy plan:")
    for cmd, desc, skip in steps:
        print(f"  {'[skip] ' if skip else ''}{desc}\n      $ {' '.join(cmd)}")

    mf = write_modelfile(str(adapter / "model-q4.gguf"), a.ctx)
    create_cmd = ["ollama", "create", a.name, "-f", mf]
    print(f"  create Ollama model\n      $ {' '.join(create_cmd)}")
    print(f"\nThen point the flywheel at it:  OLLAMA_MODEL={a.name}  (teacher), "
          f"or set_llm_backend('adapter', '{fused}') for the student.")

    if a.run:
        for cmd, desc, skip in steps:
            if skip:
                continue
            print(f"\n>>> {desc}")
            r = subprocess.run(cmd)
            if r.returncode != 0:
                print(f"  step failed: {desc}; install/locate the tool and retry.")
                sys.exit(1)
        subprocess.run(create_cmd)


if __name__ == "__main__":
    main()
